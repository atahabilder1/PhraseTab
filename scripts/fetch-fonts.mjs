/**
 * Download WordTab's typefaces into `public/fonts/` and generate `fonts.css`.
 *
 * The New Tab page must not make a network request when it opens (PLAN §15)
 * and must not leak a request to a third party on every tab (PLAN §16), so the
 * fonts are bundled with the extension rather than linked from Google Fonts.
 *
 * Only the `latin` subset is fetched. Bangla and Chinese
 * translations deliberately fall back to system fonts — bundling Noto Sans
 * Bengali and a Simplified Chinese face would add megabytes to a page whose
 * whole point is opening instantly.
 *
 * Both families are licensed under the SIL Open Font License 1.1; see
 * THIRD_PARTY_NOTICES.md.
 *
 * Run with: npm run fonts
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'fonts');

// A browser UA is required: the css2 endpoint serves woff2 only to browsers
// that advertise support, and falls back to ttf otherwise.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/** The families we ship, in the roles they play in the UI. */
const FAMILIES = [
  {
    // Headword (500) and example sentence (italic 400). Static instances: the
    // variable optical-size axis is lovely but costs ~90 KB we do not need for
    // two fixed sizes.
    query: 'Newsreader:ital,wght@0,500;1,400',
    slug: 'newsreader',
  },
  {
    // Definitions, translations, buttons.
    query: 'IBM+Plex+Sans:wght@400;500',
    slug: 'plex-sans',
  },
  {
    // Metadata: part of speech, difficulty, IPA, labels, key hints.
    query: 'IBM+Plex+Mono:wght@400;500',
    slug: 'plex-mono',
  },
];

/**
 * Subsets to keep. `latin` alone covers the English UI and the entire English
 * dataset; `latin-ext` would double the payload for accented characters the
 * vocabulary never uses.
 */
const KEEP_SUBSETS = new Set(['latin']);

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`);
  return response.text();
}

async function fetchBinary(url) {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

/**
 * Split a Google Fonts stylesheet into blocks of
 * `/* subset *\/ @font-face { ... }`, keeping the subset comment that precedes
 * each rule so we know which ones to keep.
 */
function parseFaces(css) {
  const faces = [];
  const pattern = /\/\*\s*([\w-[\]]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let match;
  while ((match = pattern.exec(css)) !== null) {
    faces.push({ subset: match[1], block: match[2] });
  }
  return faces;
}

function readDeclaration(block, property) {
  const match = new RegExp(`${property}:\\s*([^;]+);`).exec(block);
  return match ? match[1].trim() : '';
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const rules = [];
  let totalBytes = 0;

  for (const family of FAMILIES) {
    const css = await fetchText(
      `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`,
    );

    let index = 0;
    for (const face of parseFaces(css)) {
      if (!KEEP_SUBSETS.has(face.subset)) continue;

      const urlMatch = /url\((https:\/\/[^)]+\.woff2)\)/.exec(face.block);
      if (!urlMatch) continue;

      const style = readDeclaration(face.block, 'font-style') || 'normal';
      const fileName = `${family.slug}-${style}-${face.subset}-${index}.woff2`;
      index += 1;

      const bytes = await fetchBinary(urlMatch[1]);
      await writeFile(join(OUT_DIR, fileName), bytes);
      totalBytes += bytes.length;

      // Rewrite the remote URL to the path the extension serves it from, and
      // keep the unicode-range so the browser only downloads what it needs.
      rules.push(
        face.block
          .replace(urlMatch[0], `url("./fonts/${fileName}")`)
          .replace(/\s*font-display:[^;]+;/, '\n  font-display: block;'),
      );

      console.log(`  ${fileName}  ${(bytes.length / 1024).toFixed(1)} KB`);
    }
  }

  const header = [
    '/*',
    ' * Generated by scripts/fetch-fonts.mjs — do not edit by hand.',
    ' *',
    ' * Newsreader and IBM Plex are licensed under the SIL Open Font License 1.1.',
    ' * See THIRD_PARTY_NOTICES.md for the full notices.',
    ' *',
    ' * font-display: block (not swap) because the New Tab page renders a single',
    ' * short headword: a flash of fallback text is more jarring than a few',
    ' * milliseconds of nothing, and the files are local so the wait is tiny.',
    ' */',
    '',
  ].join('\n');

  await writeFile(join(OUT_DIR, '..', 'fonts.css'), `${header}${rules.join('\n\n')}\n`);

  console.log(`\n${rules.length} faces, ${(totalBytes / 1024).toFixed(1)} KB total`);
  console.log('wrote public/fonts.css');
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
